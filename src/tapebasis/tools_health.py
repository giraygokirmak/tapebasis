"""Ops tools: provider health, drift report and a self-describing tool map."""
from __future__ import annotations

from typing import Any

from .health import MONITOR, PROVIDERS
from .providers_state import DataProvider, envelope, provider_from_answered
from .reconcile import field_source

READ_ONLY = {"readOnlyHint": True, "destructiveHint": False, "openWorldHint": True}


async def tapebasis_health(refresh: bool = False) -> dict[str, Any]:
    """Probe every upstream and report whether any provider's API drifted.

    Every other tool reads the cached verdict from this monitor and adds a
    warning when a provider's upstream schema has changed or is down. Call this
    with ``refresh=True`` to force an immediate re-probe (otherwise the cached
    result is reused for ``TAPEBASIS_HEALTH_TTL`` seconds).

    The report also carries ``rate_limits``: per-provider pacing, cooldown and
    cache state. A provider can be ``OK`` and still be cooling down after a
    ``429``, which is what an agent needs to know before it retries.

    Args:
        refresh: Force fresh probes instead of using the cached verdict.

    Returns:
        Envelope whose ``data`` carries ``providers`` (``OK``/``DRIFT``/
        ``DOWN``/``UNKNOWN`` per provider), ``degraded``, ``issues``,
        ``rate_limits`` and the per-probe baseline comparison.
    """
    MONITOR.ensure_started()
    if refresh or not MONITOR.results:
        await MONITOR.run_once(force=True)

    summary = MONITOR.summary()
    statuses = summary["providers"]
    responding = [name for name, status in statuses.items() if status in ("OK", "DRIFT")]
    provider = provider_from_answered(responding)

    warnings = [
        f"{issue['provider']} {issue['status']}: {issue['probe']}, {issue['message']}"
        for issue in summary["issues"]
    ]
    if summary["degraded"]:
        statuses_note = (
            "Provider health problem detected. Any tool response will carry this "
            "warning until the upstream is fixed or recovered."
        )
        warnings.insert(0, statuses_note)
    for name, state in (summary.get("rate_limits") or {}).items():
        if state.get("cooling_down_s", 0) > 0:
            warnings.append(
                f"{name} is rate-limit cooling down for another "
                f"{state['cooling_down_s']}s (block streak {state.get('block_streak')})"
            )

    return envelope(
        summary,
        provider=provider,
        warnings=warnings,
        degraded=summary["degraded"],
        providers_answered=responding,
        sources={name: "health probe" for name in statuses},
        extra={"schema_drift": summary["issues"]},
    )


async def tapebasis_tool_map() -> dict[str, Any]:
    """List every tool, which providers back it, and how it is cross-checked.

    Useful for an agent that needs to know whether a given capability is
    multi-source (``ALL``, which can include ``SA`` or ``BLOOMBERG``), served by
    a single provider (``TRADINGVIEW``/``FINVIZ``/``YAHOO``/``SA``/
    ``BLOOMBERG``) or analysis generated by one provider only. This tool
    performs no upstream requests.
    """
    from .catalog import TOOL_CATALOG

    rows = [dict(row) for row in TOOL_CATALOG]
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["providers"]] = counts.get(row["providers"], 0) + 1
    # A tool's provider set is catalogue metadata, not field provenance, so it
    # lives under its own key. Putting it in `fields` made the map speak about
    # tools in the slot every other response reserves for data fields.
    tool_providers = {
        str(row["name"]): str(row["providers"])
        for row in rows
        if str(row["providers"]) in DataProvider.__members__
    }
    return envelope(
        {"tools": rows, "count": len(rows), "by_provider": counts},
        provider=DataProvider.ALL,
        providers_answered=[*PROVIDERS, "BLOOMBERG"],
        fields={name: field_source(provider, [provider], None)
                for name, provider in tool_providers.items()},
        warnings=[
            *MONITOR.warnings_for(PROVIDERS),
            "All providers in `providers_answered` are reconciliation legs of at "
            "least one tool. Bloomberg gates on the TLS fingerprint, so an httpx "
            "health probe there would report a false outage; it is therefore the "
            "one leg with no health probe in `providers`/`schema_drift`. The "
            "bloomberg_* tools ask that provider alone and are single-source by "
            "construction.",
        ],
        degraded=MONITOR.degraded(),
        sources={"catalog": "local tool metadata"},
    )


def register(mcp) -> int:
    """Register this module's tools on *mcp*; returns the number added."""
    mcp.add_tool(
        tapebasis_health,
        name="tapebasis_health",
        title="Provider Health & Schema Drift",
        description=tapebasis_health.__doc__,
    )
    mcp.add_tool(
        tapebasis_tool_map,
        name="tapebasis_tool_map",
        title="Tool / Provider Map",
        description=tapebasis_tool_map.__doc__,
    )
    return 2
